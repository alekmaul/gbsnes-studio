/*
 * compileSnesSfx.js - v4 follow-up: a project's own assets/sounds/*.wav ->
 * real BRR sound effects, for Sound: Play Effect's "custom" type.
 *
 * Modeled on compileSnesMusic.js's shape (shells out to a vendored tool,
 * generates a src/res/*.asm + a res/*.h), not Font/Emote's in-process-decode
 * shape, since this needs the external `snesbrr` BRR encoder (vendored
 * under buildTools/<platform>-<arch>/pvsneslib/devkitsnes/tools/).
 *
 * Each project sound effect -> `snesbrr -e in.wav out.brr`, one real
 * assembled data block per asset (src/res/sfx_custom.asm, same "graphic/
 * audio assets are 65816 source" scheme compileSnesData.js's own backgrounds/
 * sprite sheets use - see that file's header comment). A generated
 * res/sfx_custom.h declares the extern symbols + byte lengths + a
 * SFX_CUSTOM_TABLE initializer music.c's own static table is built from.
 *
 * Indexing is positional and never renumbered: entry i always corresponds to
 * projectData.soundEffects[i], matching the index getSfxIndex() (src/lib/
 * events/helpers.js) resolves at script-compile time - an asset that fails
 * to encode still gets its own table slot (length 0, SoundPlayCustomEffect
 * no-ops on it) rather than being dropped and shifting every later index,
 * the same "never renumber, fail that one slot instead" rule
 * compileSnesMusic.js's own convertTrack already follows for music tracks.
 *
 * No project sound effects -> this is a no-op: NUM_SOUND_EFFECTS stays at
 * assets.h's own 0 default and music.c's `#if NUM_SOUND_EFFECTS > 0` guard
 * means res/sfx_custom.h is never even #included, so it doesn't need to
 * exist on disk at all in that (overwhelmingly common) case.
 */
import childProcess from "child_process";
import fs from "fs-extra";
import Path from "path";
import { assetFilename } from "../helpers/gbstudio";
import { pathExists } from "../helpers/fsCopy";
import { resolvePvsHome } from "./buildSnesRom";

const run = (cmd, args, cwd) =>
  new Promise((resolve, reject) => {
    const child = childProcess.spawn(cmd, args, { cwd, shell: false });
    let out = "";
    child.stdout.on("data", (d) => {
      out += d.toString();
    });
    child.stderr.on("data", (d) => {
      out += d.toString();
    });
    child.on("error", reject);
    child.on("close", (code) =>
      code === 0
        ? resolve(out)
        : reject(new Error(`snesbrr failed (exit ${code})\n${out.trim()}`))
    );
  });

const sfxCustomAsm = (entries) => {
  const lines = [
    ";************************************************",
    "; Project sound-effect BRR samples (Sound: Play Effect, custom type).",
    "; Generated by src/lib/compiler/compileSnesSfx.js.",
    ";************************************************",
    "",
    '.include "hdr.asm"',
    "",
    '.section "sfx_custom_rodata" superfree',
    "",
  ];
  entries.forEach(({ index, len }) => {
    lines.push(`sfx_custom_${index}:`);
    // A failed encode still needs a real label (the C side's extern char
    // still references it) - one placeholder byte instead of an .incbin,
    // matching SoundPlayCustomEffect's own len==0 no-op (never played).
    lines.push(len > 0 ? `.incbin "res/sfx_custom_${index}.brr"` : ".db $00");
    lines.push("");
  });
  lines.push(".ends", "");
  return lines.join("\n");
};

const sfxCustomHeader = (entries) => {
  const lines = [
    "/* Generated by src/lib/compiler/compileSnesSfx.js. */",
    "#ifndef SFX_CUSTOM_H",
    "#define SFX_CUSTOM_H",
    "",
  ];
  entries.forEach(({ index }) => lines.push(`extern char sfx_custom_${index};`));
  lines.push("");
  entries.forEach(({ index, len }) => lines.push(`#define SFX_CUSTOM_LEN_${index} ${len}`));
  lines.push("", "#define SFX_CUSTOM_TABLE { \\");
  entries.forEach(({ index }, i) => {
    const isLast = i === entries.length - 1;
    const entry = `  { (u8 *)&sfx_custom_${index}, SFX_CUSTOM_LEN_${index} }`;
    // Every line of a multi-line #define needs its own trailing backslash
    // except the one that actually ends the macro - which must close the
    // brace itself (not a bare standalone "}" on its own line) or the
    // macro body is left unbalanced and the brace becomes a dangling
    // top-level declaration (caught via a real 816-tcc "declaration
    // expected" build failure on exactly this line).
    lines.push(isLast ? `${entry} }` : `${entry}, \\`);
  });
  lines.push("", "#endif", "");
  return lines.join("\n");
};

const compileSnesSfx = async ({
  soundEffects = [],
  projectRoot,
  buildRoot = "/tmp",
  progress = () => {},
  warnings = () => {},
} = {}) => {
  if (soundEffects.length === 0) {
    return;
  }

  let snesbrr;
  try {
    const pvsHome = await resolvePvsHome({ progress });
    const ext = process.platform === "win32" ? ".exe" : "";
    const candidate = Path.join(pvsHome, "devkitsnes", "tools", `snesbrr${ext}`);
    if (!(await pathExists(candidate))) {
      throw new Error(`not vendored for ${process.platform}-${process.arch}`);
    }
    snesbrr = candidate;
  } catch (e) {
    warnings(
      `Could not find the snesbrr BRR encoder (${e.message}) - custom sound effects will be silent in-game`
    );
    return;
  }

  const workDir = Path.join(buildRoot, "obj", "sfx");
  await fs.ensureDir(workDir);
  await fs.ensureDir(Path.join(buildRoot, "res"));
  await fs.ensureDir(Path.join(buildRoot, "src", "res"));

  const entries = [];
  for (let i = 0; i < soundEffects.length; i++) {
    const sfx = soundEffects[i];
    // eslint-disable-next-line no-await-in-loop
    try {
      const srcWav = assetFilename(projectRoot, "sounds", sfx);
      const brrPath = Path.join(workDir, `sfx_${i}.brr`);
      // eslint-disable-next-line no-await-in-loop
      await run(snesbrr, ["-e", srcWav, brrPath]);
      // eslint-disable-next-line no-await-in-loop
      const len = (await fs.stat(brrPath)).size;
      entries.push({ index: i, len });
      progress(`Encoded sound effect ${sfx.name || sfx.filename}`);
    } catch (e) {
      warnings(
        `Could not encode sound effect "${sfx.filename}" (${e.message}) - it will be silent in-game`
      );
      entries.push({ index: i, len: 0 });
    }
  }

  const copies = entries
    .filter(({ len }) => len > 0)
    .map(({ index }) =>
      fs.copy(
        Path.join(workDir, `sfx_${index}.brr`),
        Path.join(buildRoot, "res", `sfx_custom_${index}.brr`)
      )
    );
  await Promise.all(copies);

  await fs.writeFile(
    Path.join(buildRoot, "src", "res", "sfx_custom.asm"),
    sfxCustomAsm(entries)
  );
  await fs.writeFile(
    Path.join(buildRoot, "res", "sfx_custom.h"),
    sfxCustomHeader(entries)
  );

  progress(`Compiled ${entries.length} custom sound effect(s)`);
};

export default compileSnesSfx;
